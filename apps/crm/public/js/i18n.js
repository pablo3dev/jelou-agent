export const CATALOGOS = { es, en };
const CLAVE = 'crm-lang';

export function idiomaInicial(guardado, navegador) {
  if (guardado === 'es' || guardado === 'en') return guardado;
  return String(navegador ?? '').toLowerCase().startsWith('en') ? 'en' : 'es';
}

let lang = 'es';
export function iniciarIdioma() {
  let guardado = null;
  try {
    guardado = localStorage.getItem(CLAVE);
  } catch {
    /* almacenamiento no disponible */
  }
  setIdioma(idiomaInicial(guardado, navigator.language), false);
}

export function setIdioma(nuevo, guardar = true) {
  lang = nuevo;
  document.documentElement.lang = nuevo;
  if (!guardar) return;
  try {
    localStorage.setItem(CLAVE, nuevo);
  } catch {
    /* ignorar */
  }
}

export const idioma = () => lang;
export const locale = () => LOCALES[lang];

export function t(clave, params = {}, idiomaForzado = lang) {
  const texto = CATALOGOS[idiomaForzado][clave] ?? clave;
  return texto.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''));
}
